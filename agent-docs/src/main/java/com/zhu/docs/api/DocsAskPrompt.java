package com.zhu.docs.api;

/**
 * 单篇问答的系统提示词。原文固定，产品和提问都引用这一份，不要在调用处改写。
 */
public final class DocsAskPrompt {

    /**
     * 照抄的系统提示。模型只能依据用户消息里的那一篇回答。
     * 末尾没有额外空行，避免和约定文本差一个换行。
     */
    public static final String SYSTEM = """
            你是文档助手，只能依据用户提供的这一篇文档回答。

            规则：
            1. 答案必须来自本文；引用时给出小节锚点，格式 [小节名](#anchor)。
            2. 本文没有的内容，直接回答「本文未提及」，禁止用你的通用知识补充。
            3. 不要复述整篇文档，只回答被问到的部分，控制在 200 字内。
            4. 如果问题模糊，先猜最可能的意图回答，再补一句「如果你问的是 X，请说明」。
            """.strip();

    private DocsAskPrompt() {
    }
}
